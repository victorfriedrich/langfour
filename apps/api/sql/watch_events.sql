-- watch_events: which videos a user watched, and how much of each.
--
-- One row per user and video. Three sources write it:
--
--   desktop  the extension counted 70% of the video played on youtube.com
--   history  the extension read youtube.com/feed/history with the user's own
--            sign-in, after their consent; the red progress bar gives `share`
--   manual   the web Videos page's "Hide & mark as seen" (mark_video_as_seen)
--
-- A row is "watched" when it isn't unmarked and either 70% was played, the
-- share is unknown, or the user marked it by hand. A history row under 70%
-- is a video the user started and left: kept, so a later read can see the bar
-- grow, but not watched. Unmark sets unmarked_at rather than deleting, so the
-- next history read doesn't bring the video straight back; watching it again
-- on desktop, or the history bar growing past 70%, marks it again. The rules
-- live in apps/api/watch.py.
--
--   watched_at   when it was watched; null for history rows from before the
--                first read, whose day the history page doesn't say
--   share        0..1 of the video played, when known
--   language     the video's language; null for 3 old videos_seen rows that
--                are in no index
--
-- videos_seen becomes a view over the watched rows, so its readers keep
-- working unchanged: get_seen_video_ids (web Videos page) and
-- recommender.get_seen_videos (API, service role). Its one writer,
-- mark_video_as_seen, now writes here. Rows move across with their ids; the
-- old table goes to the archive schema rather than being dropped.
--
-- Also userdata.watch_recap_closed_on: the day whose recap ("Yesterday on
-- YouTube") the user put away with "Not now", so it stays away on the web and
-- in the extension.
--
-- HOW THIS GETS APPLIED: through the Supabase connector, like the other files
-- here, in one transaction. Not idempotent past step 2: run it once.

begin;

-- 1. The table.
create table public.watch_events (
    id          bigint generated by default as identity primary key,
    user_id     uuid not null references auth.users (id) on delete cascade,
    video_id    text not null check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
    language    text check (language in ('es', 'de', 'it', 'fr')),
    watched_at  timestamptz default now(),
    share       real check (share between 0 and 1),
    source      text not null default 'manual' check (source in ('desktop', 'history', 'manual')),
    unmarked_at timestamptz,
    created_at  timestamptz not null default now(),
    unique (user_id, video_id)
);

create index watch_events_user_time on public.watch_events (user_id, watched_at);

alter table public.watch_events enable row level security;

-- Own rows only. Insert and update stay open to the user because
-- mark_video_as_seen runs as them (security invoker); the extension's
-- sources go through the API with the service role.
create policy watch_events_select_own on public.watch_events
    for select to authenticated using (user_id = (select auth.uid()));
create policy watch_events_insert_own on public.watch_events
    for insert to authenticated with check (user_id = (select auth.uid()));
create policy watch_events_update_own on public.watch_events
    for update to authenticated
    using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy watch_events_delete_own on public.watch_events
    for delete to authenticated using (user_id = (select auth.uid()));

revoke all on public.watch_events from anon;

-- 2. videos_seen's rows, with their ids and times. The language comes from
-- the queue or the scores, else the user's language.
insert into public.watch_events (id, user_id, video_id, language, watched_at, source, created_at)
select v.id, v.user_id, v.video_id,
       coalesce(q.lang, s.language, u.default_language),
       v.seen_at, 'manual', v.seen_at
from public.videos_seen v
left join public.video_queue q on q.video_id = v.video_id
left join public.video_scores s on s.video_id = v.video_id
left join public.userdata u on u.user_id = v.user_id
where v.user_id is not null and v.video_id is not null;

select setval(pg_get_serial_sequence('public.watch_events', 'id'),
              greatest((select max(id) from public.watch_events), 1));

-- 3. The old table out of the way, kept.
alter table public.videos_seen set schema archive;
alter table archive.videos_seen rename to videos_seen_2026_11;
revoke all on archive.videos_seen_2026_11 from anon, authenticated;

-- 4. videos_seen as the watched rows. security_invoker, so RLS on
-- watch_events applies to whoever reads it. Mirrors watch.is_watched.
create view public.videos_seen with (security_invoker = true) as
select id, user_id, video_id, coalesce(watched_at, created_at) as seen_at
from public.watch_events
where unmarked_at is null
  and (share is null or share >= 0.7 or source = 'manual');

revoke all on public.videos_seen from anon;
grant select on public.videos_seen to authenticated, service_role;

-- 5. Its writer. Marking by hand also brings back a video the user unmarked.
-- The Videos page lists the user's language, so that is the video's.
-- (video_scores would be exact, but only the service role may read it.)
create or replace function public.mark_video_as_seen(input_video_id text)
returns void
language plpgsql
set search_path to 'public', 'pg_temp'
as $function$
begin
    insert into public.watch_events (user_id, video_id, language, source)
    values (
        auth.uid(), input_video_id,
        (select default_language from public.userdata where user_id = auth.uid()),
        'manual'
    )
    on conflict (user_id, video_id) do update
        set source = 'manual', unmarked_at = null,
            watched_at = coalesce(watch_events.watched_at, now());
end;
$function$;

-- get_seen_video_ids reads public.videos_seen and needs no change.

-- 6. "Not now" on the recap.
alter table public.userdata add column if not exists watch_recap_closed_on date;

commit;

